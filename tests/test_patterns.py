@pytest.mark.parametrize(
    "text",
    [
        # «суд» в бытовом смысле — не название суда.
        "Истец обратился в суд с исковым заявлением.",
        "Суд первой инстанции неполно выяснил обстоятельства дела.",
        # Слово-тип рядом с «судья» не должно превращаться в название суда.
        "Военный судья вынес постановление.",
    ],
)
def test_court_ignores_generic_mentions(text):
    assert _match("court", text) is None


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("в составе судьи Петровой А.С.", "Петровой А.С."),
        ("председательствующего судьи Иванова И.И.", "Иванова И.И."),
        # Регрессия: «Ё» — отдельная кодовая позиция и в диапазон [А-Я] не
        # входит, поэтому такие фамилии молча терялись.
        ("в составе судьи Ёлкиной А.Б.", "Ёлкиной А.Б."),
        # Фамилия через дефис.
        ("судья Иванов-Петров И.И.", "Иванов-Петров И.И."),
        # Начало предложения: паттерн не должен зависеть от регистра слова «судья».
        ("Судья Смирнов А.А. вынес постановление.", "Смирнов А.А."),
        # Инициалы могут быть разделены пробелом.
        ("судья Смирнов А. А.", "Смирнов А. А."),
        # Падежные формы слова «судья».
        ("дело рассмотрено судьёй Кузнецовой М.В.", "Кузнецовой М.В."),
        ("дело рассмотрено судьей Кузнецовой М.В.", "Кузнецовой М.В."),
    ],
)
def test_judge_names(text, expected):
    assert _match("judge", text) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("в размере 500 000 рублей", "500 000"),
        ("в размере 500000 руб.", "500000"),
        ("в размере 1 234 567,89 рублей", "1 234 567,89"),
        ("на сумму 45 300.50 руб.", "45 300.50"),
    ],
)
def test_claim_amount_formats(text, expected):
    assert _match("claim_amount", text) == expected
