"""Тесты regex-правил изолированно от NER.

Natasha здесь не участвует: LEGAL_PATTERNS — чистые regex, и проверять их
через публичный extract() значит гонять полный NER-пайплайн ради проверки
одного `re.search`. Разбор сущностей целиком остаётся в test_extractor.py.
"""

import pytest

from src.extractor.patterns import LEGAL_PATTERNS


def _match(key: str, text: str) -> str | None:
    match = LEGAL_PATTERNS[key].search(text)
    return match.group(1).strip() if match else None


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # Арбитраж — форматы, которые поддерживались и раньше.
        ("Дело № А40-12345/2024", "А40-12345/2024"),
        ("дело №А12-1234/2024", "А12-1234/2024"),
        ("Дело № СИП-15/2024", "СИП-15/2024"),
        ("дело № Ф05-6789/26", "Ф05-6789/26"),
        # Общая юрисдикция: номер начинается с цифр, а не с кода суда.
        ("дело № 2-1234/2024", "2-1234/2024"),
        ("Административное дело № 2а-500/2024", "2а-500/2024"),
        ("Уголовное дело № 1-45/2024", "1-45/2024"),
        ("апелляционное дело № 33-4567/2024", "33-4567/2024"),
        ("дело № 88-1500/2025", "88-1500/2025"),
        # Верховный Суд и кассация: номер длиннее и без дроби.
        ("дело № 5-КГ24-15-К2", "5-КГ24-15-К2"),
        ("дело № 18-КАД23-5-К4", "18-КАД23-5-К4"),
        ("дело № 41-УД23-11", "41-УД23-11"),
        # Номер может вводиться не только знаком «№».
        ("по делу 2-77/2025 вынесено решение", "2-77/2025"),
        ("Дело N А40-999/2023", "А40-999/2023"),
    ],
)
def test_case_number_formats(text, expected):
    assert _match("case_number", text) == expected


@pytest.mark.parametrize(
    "text",
    [
        # Без «№» или слова «дело» короткий номер общей юрисдикции неотличим
        # от пункта договора или диапазона — такое совпадение нам не нужно.
        "Пункт 2-3 соглашения был нарушен.",
        "Стороны согласовали срок 10-15/2024 рабочих дней.",
    ],
)
def test_case_number_requires_explicit_marker(text):
    assert _match("case_number", text) is None


