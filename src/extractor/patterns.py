"""Regex-паттерны для юридических текстов.

Паттерны намеренно покрывают несколько распространённых форматов российских
судебных актов (разные коды судов, 2- и 4-значные года, суммы с разделителями
разрядов и копейками), а не один жёстко зашитый пример.
"""

import re
from re import Pattern

LEGAL_PATTERNS: dict[str, Pattern[str]] = {
    # А40-12345/2024, СИП-15/2024, Ф05-6789/26 и т.п.
    "case_number": re.compile(r"№\s*([А-Я]{1,4}\d{0,3}-\d+/\d{2,4})"),
    "court": re.compile(r"(Арбитражный\s+суд\s+.+?)(?=\s+в\s+составе|[.,;])"),
    # суммы с пробелами как разделителями разрядов и опциональной копеечной частью
    "claim_amount": re.compile(r"(?:в\s+размере|сумм[ауе])\s+([\d\s]+(?:[.,]\d+)?)\s*(?:руб|рублей|₽)"),
    "judge": re.compile(r"(?:судь[яи])\s+([А-Я][а-яё]+\s+[А-Я]\.[А-Я]\.)"),
}
