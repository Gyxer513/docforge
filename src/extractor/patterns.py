"""Regex-паттерны для юридических текстов.

Паттерны намеренно покрывают несколько распространённых форматов российских
судебных актов (разные коды судов, 2- и 4-значные года, суммы с разделителями
разрядов и копейками), а не один жёстко зашитый пример.

Покрыт не только арбитраж, но и суды общей юрисдикции: районные, городские,
областные, военные, кассационные и апелляционные суды общей юрисдикции,
Верховный и Конституционный Суд РФ. Раньше `court` начинался со слова
«Арбитражный», а `case_number` требовал кириллических букв перед цифрами —
из-за этого решение районного суда («Замоскворецкий районный суд города
Москвы», дело № 2-1234/2024) не давало вообще ни одного совпадения, а
собственная апелляция DocForge («Девятый арбитражный апелляционный суд»)
не опознавалась как суд, потому что название начинается с порядкового
числительного.

Известное ограничение: акты мировых судей («Мировой судья судебного участка
№ 100») не распознаются как суд — там название строится вокруг судебного
участка, а не слова «суд», это отдельный формат.
"""

import re
from re import Pattern

# ──────────────────────────────────────────────────────────────────────────
# Номер дела
# ──────────────────────────────────────────────────────────────────────────

# Номеру дела должно предшествовать «№», «N» или само слово «дело» — без
# этого требования короткие номера общей юрисдикции (2-1234/2024) начали бы
# ловиться в любом перечислении пунктов и диапазоне дат.
_CASE_PREFIX = r"(?:(?:№|N)\s*|дел[оауе]\s+)"

# Арбитраж: А40-12345/2024, А12-1234/2024, СИП-15/2024, Ф05-6789/26.
_CASE_ARBITRATION = r"[А-ЯЁ]{1,4}\d{0,3}-\d+/\d{2,4}"

# Кассация и Верховный Суд: 5-КГ24-15-К2, 18-КАД23-5-К4, 41-УД23-11.
_CASE_CASSATION = r"\d{1,3}-[А-ЯЁ]{2,4}\d{2}-\d+(?:-[А-ЯЁ]\d+)?"

# Общая юрисдикция: 2-1234/2024 (гражданское), 2а-500/2024 (административное),
# 1-45/2024 (уголовное), 33-1234/2024 (апелляция), 5-15/2025 (КоАП).
_CASE_GENERAL = r"\d{1,3}[а-яё]?-\d+/\d{2,4}"

# Порядок альтернатив важен: кассационный номер начинается с цифр так же, как
# номер общей юрисдикции, но длиннее — если поставить общий первым, он оторвёт
# от «5-КГ24-15-К2» только начало.
_CASE_NUMBER = rf"(?:{_CASE_ARBITRATION}|{_CASE_CASSATION}|{_CASE_GENERAL})"

# ──────────────────────────────────────────────────────────────────────────
# Название суда
# ──────────────────────────────────────────────────────────────────────────

# Слово, по которому мы опознаём, что перед нами название суда, а не слово
# «суд» в бытовом смысле («обратился в суд», «суд первой инстанции»).
# \w+ на конце — чтобы ловить любые падежные формы («Арбитражного»).
_COURT_KIND = (
    r"[Аа]рбитражн\w+|[Рр]айонн\w+|[Мм]ежрайонн\w+|[Гг]ородск\w+|[Оо]бластн\w+|"
    r"[Кк]раев\w+|[Рр]еспубликанск\w+|[Оо]кружн\w+|[Гг]арнизонн\w+|[Фф]лотск\w+|"
    r"[Вв]оенн\w+|[Аа]пелляционн\w+|[Кк]ассационн\w+|[Вв]ерховн\w+|"
    r"[Кк]онституционн\w+|[Уу]ставн\w+"
)

# Определение перед типом суда: порядковое числительное («Девятый», «Второй»)
# или название района («Замоскворецкий»).
_COURT_ADJECTIVE = r"[А-ЯЁа-яё]+(?:ый|ий|ой)"

# «суд», «суда», «суде», «судом» — но не «судья»/«судьи»: \b после окончания
# не даст зацепиться за «военный судья».
_COURT_WORD = r"[Сс]уд(?:а|е|у|ом|ы|ов|ам|ами)?\b"

# Суд по интеллектуальным правам — единственный суд, в названии которого нет
# слова-типа, поэтому он задан отдельной альтернативой. Номера его дел
# (СИП-15/2024) паттерн case_number разбирал и раньше, а сам суд — нет.
_COURT_SIP = r"[Сс]уд по интеллектуальным правам"

_COURT_STRUCTURED = (
    rf"(?:{_COURT_ADJECTIVE}\s+){{0,2}}(?:{_COURT_KIND})(?:\s+{_COURT_ADJECTIVE}){{0,2}}\s+{_COURT_WORD}"
)

_COURT_NAME = rf"(?:{_COURT_SIP}|{_COURT_STRUCTURED})"

# Хвост названия («города Москвы», «г. Москвы», «Российской Федерации»,
# «Свердловской области», «общей юрисдикции») собирается из закрытого набора
# слов, а не из «любого слова до знака препинания»: иначе во фразе
# «Арбитражный суд Московского округа отменил решение» в название попал бы и
# глагол, и всё, что стоит до точки.
_COURT_TAIL_WORD = (
    r"(?:[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?"
    r"|города|город|области|округа|края|республики|автономного|общей|юрисдикции"
    r"|г\.|гор\.)"
)
_COURT_TAIL = rf"(?:\s+{_COURT_TAIL_WORD})*"

LEGAL_PATTERNS: dict[str, Pattern[str]] = {
    "case_number": re.compile(rf"{_CASE_PREFIX}({_CASE_NUMBER})"),
    "court": re.compile(rf"({_COURT_NAME}{_COURT_TAIL})"),
    # суммы с пробелами как разделителями разрядов и опциональной копеечной частью
    "claim_amount": re.compile(r"(?:в\s+размере|сумм[ауе])\s+([\d\s]+(?:[.,]\d+)?)\s*(?:руб|рублей|₽)"),
    # Фамилия допускается через дефис («Иванов-Петров») и с «Ё» в начале
    # («Ёлкина») — обычный диапазон [А-Я] букву Ё не включает, это отдельная
    # кодовая позиция, и такие фамилии молча терялись.
    "judge": re.compile(r"[Сс]удь(?:я|и|ю|ей|ёй)\s+([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.)"),
}
